"""Agent 3: validate narrative-claim evidence against Agent 1's catalog.

This component does not assess natural-language truth. The existing Agent 1
evidence verifier remains the single implementation of reference and
registered-calculation checks.
"""

from __future__ import annotations

from collections.abc import Sequence

from app.schemas.verifier import NarrativeClaimInput, NarrativeClaimVerificationResult
from app.services.decision.evidence import (
    Claim,
    EvidenceCatalog,
    EvidenceReference,
    verify_claims,
)

_NOT_ASSESSED_LIMITATION = (
    "Natural-language claim truth was not assessed; valid evidence references "
    "and calculation IDs do not prove the statement is true."
)
_GEOMETRIC_SCORE_LIMITATION = (
    "geometric_progression_v1 is a geometric progression/composite score, "
    "not xG or a pass-success probability."
)


def verify_narrative_claims(
    claims: Sequence[NarrativeClaimInput], catalog: EvidenceCatalog
) -> list[NarrativeClaimVerificationResult]:
    """Validate references and calculation consistency for structured claims.

    Statements are carried through for traceability only. They are never parsed
    or declared semantically supported. Callers should pass structured claims
    alongside the prose generated by the Narrator; this service cannot verify
    arbitrary rendered narrative text.
    """
    inputs = [
        claim if isinstance(claim, NarrativeClaimInput) else NarrativeClaimInput.model_validate(claim)
        for claim in claims
    ]
    internal_claims = [
        Claim(
            id=claim.id,
            statement=claim.statement,
            evidence=[
                EvidenceReference(
                    kind=reference.kind,
                    id=reference.id,
                    match_id=reference.matchId,
                    detail=reference.detail,
                )
                for reference in claim.evidence
            ],
            calculation=claim.calculation,
            limitations=list(claim.limitations),
            require_full_support=claim.requireFullSupport,
        )
        for claim in inputs
    ]

    checked = verify_claims(internal_claims, catalog)
    results: list[NarrativeClaimVerificationResult] = []
    for source, result in zip(inputs, checked, strict=True):
        limitations = list(dict.fromkeys([*result.limitations, _NOT_ASSESSED_LIMITATION]))
        # Attach the score caveat only when a referenced catalog calculation is
        # registered as the composite score; never infer this from claim prose.
        references_composite = any(
            reference.kind == "calculation"
            and catalog.calculation_payloads.get(reference.id, {}).get("metric")
            == "composite_score"
            for reference in source.evidence
        )
        if references_composite:
            limitations.append(_GEOMETRIC_SCORE_LIMITATION)
        results.append(
            NarrativeClaimVerificationResult(
                claimId=result.id,
                submittedStatement=result.statement,
                evidenceValidationStatus=result.status,
                reason=result.reason,
                evidence=source.evidence,
                limitations=list(dict.fromkeys(limitations)),
            )
        )
    return results
